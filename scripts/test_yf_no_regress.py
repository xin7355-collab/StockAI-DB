#!/usr/bin/env python3
"""「日期不可倒退」守門測試(不打網路)。

踩到的事(2026-07-30,使用者拿籌碼K線對照)：
  我的 App 盤前檢視        籌碼K線(真值,同一時間)
  ─────────────────      ────────────────────
  韓股  6,024  −10.84%     韓股  5,663.24  −5.98%
  日經 62,365  −3.95%      日經 61,434.19  −1.49%
  恆指 25,311  +0.41%      恆指 25,807.92  +1.96%
  標普期 7,335 −1.75%      小S&P期 7,358.75 **+0.10%**
  那指期27,259 −2.38%      小那指期27,387.75 **+0.17%**
  道瓊期51,730 −2.29%      小道瓊期51,892   **+0.25%**

  6,023.66 × (1 − 5.98%) = 5,663.5 → 證實我存的是 **07/28** 收盤,籌碼K線是 07/29。
  而且更早一輪(前一晚)macro_risk.json 裡的韓股本來是正確的 −5.98%,
  是 04:42 那輪 yfinance 回了 07/28 的資料把它**蓋回去**。

  最嚴重的不是差一天,是**美股期貨方向相反**:07/28 三大期貨收綠、07/30 清晨翻紅。
  盤前看期貨就是為了判斷今天開盤方向,方向錯等於誤導。

  既有的 last-good 機制只在「新值是 None」時沿用舊值,擋不住「成功回應但是舊的」。

驗 _should_keep_old(new_val, new_date, old_val, old_date):
  ① 新資料比舊的舊 → 擋(保留舊值)← 這就是韓股/美股期貨那次
  ② 日期相同 → 不擋(正常覆蓋)
  ③ 新資料較新 → 不擋
  ④ 新值 None → 不擋(交給既有 last-good)
  ⑤ 任一邊沒日期 → 不擋(無法比較,寧可放過也不要誤擋成永不更新)
  ⑥ 沒有舊值可留 → 不擋(第一次抓)
  ⑦ 跨月/跨年字串比較要正確(ISO 格式字典序 = 時序)
"""
import os
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ.setdefault('SKIP_GLOBAL', '1')
for _m in ('yfinance',):
    if _m not in sys.modules:
        _s = types.ModuleType(_m)
        _s.Ticker = lambda *a, **k: None
        sys.modules[_m] = _s

import macro_miner as mm

K = mm._should_keep_old

# ① 真實案例:韓股。已存 07/29(−5.98),這次抓到 07/28(−10.84)→ 必須保留 07/29
assert K(6023.66, '2026-07-28', 5663.24, '2026-07-29') is True, '① 抓到更舊的資料必須擋住'
print('✅ ① 韓股情境:已存 07/29、抓到 07/28 → 擋住,保留 07/29(不會再倒退成前一天)')

# ①b 美股期貨方向相反的那組
assert K(7334.75, '2026-07-28', 7358.75, '2026-07-29') is True, '①b 期貨舊值不可覆蓋'
print('✅ ①b 標普期情境:07/28 收綠不會覆蓋 07/29 翻紅(盤前開盤方向不會被講反)')

# ② 同一天 → 正常覆蓋(盤中多次採礦要能更新)
assert K(5700.0, '2026-07-29', 5663.24, '2026-07-29') is False, '② 同日應允許覆蓋'
print('✅ ② 同一天重抓 → 照樣覆蓋(盤中多輪採礦仍會更新)')

# ③ 較新 → 覆蓋
assert K(5500.0, '2026-07-30', 5663.24, '2026-07-29') is False, '③ 較新資料必須寫入'
print('✅ ③ 抓到更新的資料 → 正常寫入')

# ④ 新值 None → 不由本守門處理(既有 last-good 負責)
assert K(None, '2026-07-28', 5663.24, '2026-07-29') is False, '④ None 不該走本守門'
print('✅ ④ 抓失敗(None)→ 交給既有 last-good 機制,本守門不插手')

# ⑤ 缺日期 → 不擋(否則拿不到日期的來源會永遠不更新)
assert K(100.0, None, 90.0, '2026-07-29') is False, '⑤ 新日期未知不該擋'
assert K(100.0, '2026-07-29', 90.0, None) is False, '⑤ 舊日期未知不該擋'
assert K(100.0, '', 90.0, '') is False, '⑤ 空字串日期不該擋'
print('✅ ⑤ 任一邊沒日期 → 不擋(刻意保守:寧可放過,也不要誤擋成永遠不更新)')

# ⑥ 第一次抓(沒有舊值)→ 不擋
assert K(100.0, '2026-07-28', None, '2026-07-29') is False, '⑥ 沒有舊值可留就不該擋'
print('✅ ⑥ 沒有舊值(第一次抓)→ 直接寫入')

# ⑦ 跨月/跨年:ISO 日期字串的字典序剛好等於時序
assert K(1.0, '2026-06-30', 2.0, '2026-07-01') is True, '⑦ 跨月要判對'
assert K(1.0, '2025-12-31', 2.0, '2026-01-02') is True, '⑦ 跨年要判對'
assert K(1.0, '2026-07-01', 2.0, '2026-06-30') is False, '⑦ 跨月變新不可擋'
print('✅ ⑦ 跨月 / 跨年比較正確(ISO 格式字典序 = 時序)')

# ⑧ ticker 對照表必須跟實際 fetch_* 用的 ticker 一致,否則守門查不到日期等於沒作用
import inspect
src = inspect.getsource(mm)
for key, tk in {'kospi': '^KS11', 'nikkei': '^N225', 'hsi': '^HSI',
                'es_fut': 'ES=F', 'ym_fut': 'YM=F', 'nq_fut': 'NQ=F', 'vix': '^VIX'}.items():
    assert f'"{tk}"' in src, f'⑧ {key} 的 ticker {tk} 不在原始碼裡?'
    assert f'"{key}": "{tk}"' in src, f'⑧ _BIG_PLAYER_TICKERS 的 {key} 應對到 {tk}'
print('✅ ⑧ key→ticker 對照表與各 fetch_* 實際使用的 ticker 一致(對不上守門會靜默失效)')

print('\n🎉 日期不可倒退守門 八項測試全過')
